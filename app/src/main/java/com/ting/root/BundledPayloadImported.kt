        vendor: String,
        name: String,
        keywords: List<String>,
        kernel: String?,
        build: String,
        sha256: String,
        size: Long,
        shortName: String,
        source: String,
    ) = BundledPayloadCatalog.BundledPayload(
        library = library,
        vendor = vendor,
        displayName = name,
        model = keywords,
        kernelVersion = kernel,
        sha256 = sha256,
        size = size,
        shortName = shortName,
        sourcePath = source,
        command = "LD_PRELOAD=<payload> /system/bin/id",
        origin = BundledPayloadCatalog.Origin.VendorBuild,
        // 不再给每条挂「内核未知」备注 —— 83 份里 77 份读不出内核版本，
        // 逐条挂会让那句两行说明在几乎每张卡片上重复一遍，把机型列表冲得看不清。
        // 它已改到选择页的折叠说明里出现一次（见 PayloadSourceDetailSheet）。
        noteRes = 0,
        kernelUnknown = kernel == null,
        buildId = build,
    )
}
